#!/usr/bin/env node
/**
 * Generate `src/agent/enums.generated.ts` from the backend's gin `oneof=` tags.
 *
 * The backend DTOs are the authority on legal values. Agents need them *before*
 * the call, not as a 400 response after it. Rather than hand-maintaining a
 * second list (which silently drifts the moment a domain adds a state), this
 * script lifts the values out of `binding:"...oneof=a b c"` tags.
 *
 * Only fields whose value set is consistent across the whole backend are
 * exported. Ambiguous fields (`status`, `type`, `action` each mean something
 * different per domain) are skipped — a wrong enum is worse than no enum, and
 * those commands carry their values in their own summary/usage instead.
 *
 * Usage:
 *   node scripts/gen-enums.mjs           # write the file
 *   node scripts/gen-enums.mjs --check   # fail if the file is stale (CI/drift gate)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const here = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(here, '..');
const backendRoot = process.env['ITSM_BACKEND_DIR'] ?? path.resolve(cliRoot, '../itsm-backend');
const outFile = path.join(cliRoot, 'src/agent/enums.generated.ts');

/**
 * Fields whose meaning is domain-specific; a global enum would be actively
 * wrong. `provider` is a cloud vendor in CMDB and a connector name in
 * `connector revoke`; `channel` is a notification channel and, in
 * `connector send`, a conversation id. A wrong enum is worse than no enum.
 */
const AMBIGUOUS = new Set(['status', 'type', 'action', 'format', 'fileType', 'exportType', 'role', 'dataType', 'unit', 'source', 'provider', 'channel']);

/**
 * Positive allowlist: only fields that mean the same thing in every domain.
 * Adding a field here is a claim about backend-wide semantics, not a guess.
 */
const ALLOWED = new Set([
  'priority', 'defaultPriority', 'severity', 'impact', 'impactScope', 'urgency',
  'dataClassification', 'alertLevel', 'approvalMode', 'approverType', 'enterpriseType',
  'outcome', 'overallResult', 'processType', 'rejectAction', 'relatedType',
  'serviceType', 'surveyType', 'updateMode', 'chartType', 'predictionType',
]);

const files = [];
for (const sub of ['dto', 'handlers']) {
  const root = path.join(backendRoot, sub);
  if (!existsSync(root)) continue;
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, entry.name);
      if (entry.isDirectory()) { walk(p); continue; }
      if (entry.name.endsWith('.go') && !entry.name.endsWith('_test.go')) files.push(p);
    }
  };
  walk(root);
}

/** field → set of value-tuples, to detect conflicts. */
const seen = new Map();

const lineRegex = /json:"([A-Za-z][A-Za-z0-9]*)"/;
const oneofRegex = /oneof=([^"]+)/;

for (const file of files) {
  for (const line of readFileSync(file, 'utf-8').split('\n')) {
    const oneof = line.match(oneofRegex);
    if (!oneof) continue;
    const json = line.match(lineRegex);
    if (!json) continue;
    const field = json[1];
    const values = oneof[1].trim().split(/\s+/).filter((v) => /^[A-Za-z][A-Za-z0-9_]*$/.test(v) || /[\u4e00-\u9fa5]/.test(v));
    if (values.length < 2) continue;
    if (AMBIGUOUS.has(field) || !ALLOWED.has(field)) continue;
    if (!seen.has(field)) seen.set(field, new Set());
    seen.get(field).add(values.join(' '));
  }
}

/** Keep only fields where every occurrence agrees; union only when sets nest. */
const resolved = new Map();
for (const [field, tuples] of seen) {
  const lists = [...tuples].map((t) => t.split(' '));
  const union = [...new Set(lists.flat())];
  // Nested sets (one is a subset of another) are safe to widen; disjoint sets are not.
  const nested = lists.every((l) => l.every((v) => union.includes(v))) && union.length <= 8;
  if (tuples.size > 1 && !nested) continue;
  resolved.set(field, union);
}

const fields = [...resolved.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = `// AUTO-GENERATED by scripts/gen-enums.mjs from itsm-backend DTO \`oneof=\` tags.
// Do not edit by hand. Regenerate with: npm run gen:enums
// Fields whose meaning is domain-specific (status/type/action/...) are intentionally absent.

export const FIELD_ENUMS: Record<string, string[]> = {
${fields.map(([f, values]) => `  ${JSON.stringify(f)}: [${values.map((v) => JSON.stringify(v)).join(', ')}],`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const existing = existsSync(outFile) ? readFileSync(outFile, 'utf-8') : '';
  if (existing !== body) {
    console.error('✗ src/agent/enums.generated.ts is stale — run `npm run gen:enums`.');
    process.exit(1);
  }
  console.log(`✓ enums.generated.ts is in sync (${fields.length} fields).`);
  process.exit(0);
}

writeFileSync(outFile, body);
console.log(`✓ wrote src/agent/enums.generated.ts (${fields.length} fields, ${files.length} Go files scanned)`);
for (const [f, v] of fields) console.log(`  ${f}: ${v.join('|')}`);
