// 本文件是「路由声明 = 权限单一真源」的生成层（2026-09-17 批次 5，P0-E 治本）。
//
// 数据流：
//
//	router/ + handlers/ 的 RequirePermission 家族声明   （唯一手写源，人只改这里）
//	        │ ScanDeclaredPermissionRoutes（AST 扫描，route_scan.go）
//	        ▼
//	precheckRoutePermissions()                          （生成物 rbac_precheck_gen.go，禁手改）
//	        │ + precheckFallbackPolicies                 （显式回退策略，少量手写，见 rbac.go）
//	        ▼
//	ResourceActionMap = buildResourceActionMap()        （运行时预检映射）
//
// 新鲜度由 TestPrecheckMapIsFresh 守卫：改路由忘重新生成 → CI 红。

// generatePrecheckMap 从路由声明构建 (method, pattern) → Permission 映射。
//
// 同一 (method, pattern) 的多对声明分两种情况：
//   - 同一声明点（同 file:line）链式挂多个 RequirePermission（AND 语义，
//     如 POST /ai/incidents/:id/analyze 同时要求 ai:read 与 incident:read）
//     → 预检是**必要条件闸**（先拒），取首个声明对即可，路由级中间件仍完整复查；
//   - 不同声明点声明了不同权限对 → 视为口径冲突，返回错误
//     （生成层面即暴露，而不是静默取其一掩盖问题）。
func generatePrecheckMap() (map[string]map[string]Permission, error) {
	routes, err := ScanDeclaredPermissionRoutes()
	if err != nil {
		return nil, fmt.Errorf("扫描路由声明: %w", err)
	}

	type key struct{ method, path string }
	owner := map[key]string{}   // 首个声明的出处（file:line）
	pair := map[key][2]string{} // 权限对
	out := map[string]map[string]Permission{}

	for _, r := range routes {
		k := key{r.Method, r.FullPath}
		if prev, exists := pair[k]; exists {
			if prev != [2]string{r.Resource, r.Action} && owner[k] != fmt.Sprintf("%s:%d", r.File, r.RouteLine) {
				return nil, fmt.Errorf(
					"预检生成冲突：%s %s 同时声明了 %s:%s（%s）与 %s:%s（%s:%d），请先统一口径",
					r.Method, r.FullPath, prev[0], prev[1], owner[k],
					r.Resource, r.Action, r.File, r.RouteLine)
			}
			continue
		}
		owner[k] = fmt.Sprintf("%s:%d", r.File, r.RouteLine)
		pair[k] = [2]string{r.Resource, r.Action}
		if out[r.Method] == nil {
			out[r.Method] = map[string]Permission{}
		}
		out[r.Method][r.FullPath] = Permission{Resource: r.Resource, Action: r.Action}
	}
	return out, nil
}

// GeneratePrecheckSource 生成 rbac_precheck_gen.go 的完整源码（确定性输出，便于 diff 审查）。
func GeneratePrecheckSource() ([]byte, error) {
	m, err := generatePrecheckMap()
	if err != nil {
		return nil, err
	}

	methods := make([]string, 0, len(m))
	for method := range m {
		methods = append(methods, method)
	}
	sort.Strings(methods)

	var b strings.Builder
	b.WriteString(`// Code generated by cmd/authz-gen from route declarations. DO NOT EDIT.
//
// 权限单一真源体系（2026-09-17 批次 5，P0-E 治本）：
// 本文件的每个条目都生成自 router/ 与 handlers/ 中的 RequirePermission 家族声明
// （gin 路径参数 :id/*xxx 归一为通配符 *）。修改权限口径请改路由声明后重新生成：
//
//	cd itsm-backend && go run ./cmd/authz-gen
//
// 手改本文件会被 TestPrecheckMapIsFresh 守卫拒绝。
// 族级回退策略（覆盖未声明路由的缺省预检）在 rbac.go 的 precheckFallbackPolicies。

package middleware

// precheckRoutePermissions 路由级预检条目：键=HTTP 方法，值=路径模式→权限。
func precheckRoutePermissions() map[string]map[string]Permission {
	return map[string]map[string]Permission{
`)
	for _, method := range methods {
		paths := make([]string, 0, len(m[method]))
		for p := range m[method] {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		fmt.Fprintf(&b, "\t\t%s: {\n", quoteGo(method))
		for _, p := range paths {
			perm := m[method][p]
			fmt.Fprintf(&b, "\t\t\t%s: {Resource: %s, Action: %s},\n",
				quoteGo(p), quoteGo(perm.Resource), quoteGo(perm.Action))
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t}\n}\n")

	// 生成物必须 gofmt 合规：守卫 TestPrecheckMapIsFresh 对比的是生成器原文，
	// 未经格式化的输出会被 gofmt -w 改写后导致新鲜度误报。
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("生成物格式化失败: %w", err)
	}
	return formatted, nil
}

// PrecheckGenFilePath 返回生成物的落盘路径（middleware 包目录内），与调用方 cwd 无关。
func PrecheckGenFilePath() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("无法定位 precheck_codegen.go 所在目录")
	}
	return filepath.Join(filepath.Dir(thisFile), "rbac_precheck_gen.go"), nil
}

// quoteGo 输出 Go 字符串字面量（带引号）。
func quoteGo(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
