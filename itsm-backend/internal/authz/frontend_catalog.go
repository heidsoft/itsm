package authz

// 前端权限码目录 codegen：权限码在**前端只有这一份**（构建期快照），
// 内容完全派生自本包 Definitions()。前端组件不再手写 "resource:action"
// 字符串，一律引用生成的 PERM 常量；引用了码空间不存在的码会直接
// TypeScript 编译失败（幽灵码在构建期拦截，而不是线上按钮永远不渲染）。
//
// 运行期真源仍然是 DB permissions 表；本生成物只是码空间的编译期视图，
// 与 middleware/rbac_precheck_gen.go 一样「禁手改、CI 守新鲜度」
// （守卫：internal/authz/frontend_catalog_test.go）。
//
// 重新生成：cd itsm-backend && go run ./cmd/authz-gen

import (
	"encoding/json"
	"fmt"
	"runtime"
	"strings"
)

// FrontendCatalogGenFilePath 返回前端生成物的落盘路径
// （itsm-frontend/src/lib/permissions/catalog.gen.ts）。
// 以本文件所在目录为锚向上走到仓库根，与 cwd 无关。
func FrontendCatalogGenFilePath() (string, error) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("无法定位 frontend_catalog.go 所在目录")
	}
	// internal/authz/frontend_catalog.go → 仓库根（裁掉文件名 + authz + internal + itsm-backend）
	dir := thisFile
	for i := 0; i < 4; i++ {
		dir = dir[:strings.LastIndexByte(dir, '/')]
	}
	return dir + "/itsm-frontend/src/lib/permissions/catalog.gen.ts", nil
}

// quoteTS 输出 TS 字符串字面量。复用 json.Marshal 的转义规则
// （其产物是合法的 JS/TS 字符串字面量）。
func quoteTS(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		// Definitions() 里的字符串都是简单中文/ASCII，实际不可达
		return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
	}
	return string(b)
}

// GenerateFrontendCatalogTS 渲染 catalog.gen.ts 的完整 TS 源码。
func GenerateFrontendCatalogTS() ([]byte, error) {
	defs := Definitions()
	if len(defs) == 0 {
		return nil, fmt.Errorf("Definitions() 为空，拒绝生成空权限目录")
	}

	var b strings.Builder
	b.WriteString("// Code generated by itsm-backend/cmd/authz-gen from internal/authz/catalog.go Definitions(). DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// 前端权限码的唯一一份（构建期快照）。码空间的增删只能改后端\n")
	b.WriteString("// internal/authz/catalog.go，然后重新生成本文件；引用不存在的码会在\n")
	b.WriteString("// TypeScript 编译期直接报错（幽灵码零容忍）。\n")
	b.WriteString("//\n")
	b.WriteString("// 运行期真源仍是 DB permissions 表（含风险分级 / AI 主体授权 / 审批强度）；\n")
	b.WriteString("// 本文件只承载码空间本身，不承载运行期策略。\n")
	b.WriteString("//\n")
	b.WriteString("// 重新生成：cd itsm-backend && go run ./cmd/authz-gen\n\n")

	b.WriteString("/** 权限目录条目（与后端 authz.PermissionDef 一致） */\n")
	b.WriteString("export interface PermissionCatalogEntry {\n")
	b.WriteString("  readonly code: string;\n")
	b.WriteString("  readonly resource: string;\n")
	b.WriteString("  readonly action: string;\n")
	b.WriteString("  /** 展示名（后端维护） */\n")
	b.WriteString("  readonly name: string;\n")
	b.WriteString("  /** 说明（后端维护） */\n")
	b.WriteString("  readonly description: string;\n")
	b.WriteString("}\n\n")

	b.WriteString("/** 后端权限码权威清单的构建期快照（顺序与后端 Definitions() 一致） */\n")
	b.WriteString("export const PERMISSION_CATALOG = [\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "  { code: %s, resource: %s, action: %s, name: %s, description: %s },\n",
			quoteTS(d.Code), quoteTS(d.Resource), quoteTS(d.Action), quoteTS(d.Name), quoteTS(d.Description))
	}
	b.WriteString("] as const satisfies readonly PermissionCatalogEntry[];\n\n")

	b.WriteString("/** 合法权限码联合类型：hasPermission(PERM.ticket.read) 之外的字面量会编译失败 */\n")
	b.WriteString("export type PermissionCode = (typeof PERMISSION_CATALOG)[number]['code'];\n\n")

	// PERM 嵌套对象：按 resource 分组，组内保持码空间顺序。
	b.WriteString("/** 按资源分组的权限码访问器：PERM.ticket.read === 'ticket:read' */\n")
	b.WriteString("export const PERM = {\n")
	seen := map[string]bool{}
	var order []string
	grouped := map[string][]string{}
	for _, d := range defs {
		if !seen[d.Resource] {
			seen[d.Resource] = true
			order = append(order, d.Resource)
		}
		grouped[d.Resource] = append(grouped[d.Resource], d.Action)
	}
	for _, res := range order {
		fmt.Fprintf(&b, "  %s: {\n", quoteTS(res))
		for _, act := range grouped[res] {
			fmt.Fprintf(&b, "    %s: %s,\n", quoteTS(act), quoteTS(res+":"+act))
		}
		b.WriteString("  },\n")
	}
	b.WriteString("} as const satisfies Record<string, Record<string, PermissionCode>>;\n")

	return []byte(b.String()), nil
}
