package bootstrap

import (
	"context"
	"database/sql"
	"fmt"

	"go.uber.org/zap"
)

// prepareWorkflowTemplatesIdentityMigration upgrades installations whose
// workflow_templates table was created by migration 021 with a SERIAL id
// column. Once the workflowtemplate entity entered Ent's generated code, the
// auto-migration diff expects an IDENTITY column (matching every other
// Ent-managed table) and fails hard on "unexpected attribute change (expect
// IDENTITY)" — before any versioned post-schema migration gets a chance to
// run. This compatibility hook therefore runs BEFORE client.Schema.Create.
//
// Fresh installations are unaffected: Ent creates the table itself (and
// migration 021 now uses IDENTITY as well), and the hook is a no-op when the
// column is already an identity column.
func prepareWorkflowTemplatesIdentityMigration(
	ctx context.Context,
	db *sql.DB,
	logger *zap.SugaredLogger,
) error {
	if db == nil {
		return nil
	}

	var tableExists bool
	if err := db.QueryRowContext(ctx, `
		SELECT EXISTS (
			SELECT 1
			FROM information_schema.tables
			WHERE table_schema = current_schema()
			  AND table_name = 'workflow_templates'
		)
	`).Scan(&tableExists); err != nil {
		return fmt.Errorf("inspect workflow_templates table: %w", err)
	}
	if !tableExists {
		return nil
	}

	var isIdentity bool
	if err := db.QueryRowContext(ctx, `
		SELECT COALESCE(is_identity, 'NO') = 'YES'
		FROM information_schema.columns
		WHERE table_schema = current_schema()
		  AND table_name = 'workflow_templates'
		  AND column_name = 'id'
	`).Scan(&isIdentity); err != nil {
		return fmt.Errorf("inspect workflow_templates.id: %w", err)
	}
	if isIdentity {
		return nil
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin workflow_templates identity migration: %w", err)
	}
	defer tx.Rollback()

	// 1) Detach the SERIAL default so the legacy sequence can be dropped.
	if _, err := tx.ExecContext(ctx,
		`ALTER TABLE workflow_templates ALTER COLUMN id DROP DEFAULT`); err != nil {
		return fmt.Errorf("drop workflow_templates.id default: %w", err)
	}
	// 2) Remove the legacy sequence (it will be replaced by the identity's own).
	if _, err := tx.ExecContext(ctx,
		`DROP SEQUENCE IF EXISTS workflow_templates_id_seq`); err != nil {
		return fmt.Errorf("drop workflow_templates_id_seq: %w", err)
	}
	// 3) Convert to IDENTITY (BY DEFAULT keeps explicit-id inserts working,
	//    matching Ent's expectation for every other table).
	if _, err := tx.ExecContext(ctx,
		`ALTER TABLE workflow_templates ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`); err != nil {
		return fmt.Errorf("add workflow_templates.id identity: %w", err)
	}
	// 4) Re-seed the identity sequence so the next insert cannot collide.
	if _, err := tx.ExecContext(ctx, `
		SELECT setval(
			pg_get_serial_sequence('workflow_templates', 'id'),
			GREATEST((SELECT COALESCE(MAX(id), 0) FROM workflow_templates), 1),
			true
		)`); err != nil {
		return fmt.Errorf("reseed workflow_templates identity: %w", err)
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit workflow_templates identity migration: %w", err)
	}
	logger.Infow("workflow_templates id migration: SERIAL converted to IDENTITY")
	return nil
}
