#!/usr/bin/env bash
# Generate ent code into an isolated staging directory, then sync only the
# files whose content actually changed.
#
# Usage:
#   bash scripts/entgen.sh            # generate and sync into ent/
#   bash scripts/entgen.sh --check    # generate, compare, never write ent/
#
# A failed or interrupted generation leaves ent/ untouched: the previous
# workflow wrote hundreds of half-finished files into the tracked tree and
# produced unreviewable 854-file diffs.
set -euo pipefail

MODE=apply
case "${1:-}" in
  "" | --apply) MODE=apply ;;
  --check) MODE=check ;;
  -h | --help)
    sed -n '2,9p' "${BASH_SOURCE[0]}"
    exit 0
    ;;
  *)
    echo "entgen: unknown argument: $1" >&2
    exit 2
    ;;
esac

BACKEND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CACHE_DIR="${BACKEND_DIR}/.cache/entgen"
BIN_DIR="${CACHE_DIR}/bin"
STAGE_ROOT="${CACHE_DIR}/runs"
LOG_FILE="${CACHE_DIR}/last-run.log"
mkdir -p "${BIN_DIR}" "${STAGE_ROOT}"

# The generator is pinned by entgo.io/ent in go.mod. Rebuilding whenever that
# version changes prevents stale generated code after a dependency bump.
ENT_VERSION="$(awk '$1 == "entgo.io/ent" { print $2; exit }' "${BACKEND_DIR}/go.mod")"
if [ -z "${ENT_VERSION}" ]; then
  echo "entgen: cannot resolve entgo.io/ent version from go.mod" >&2
  exit 1
fi
ENTGEN_SRC_HASH="$(cksum < "${BACKEND_DIR}/cmd/entgen/main.go" | awk '{print $1}')"
ENTGEN_BIN="${BIN_DIR}/entgen-${ENT_VERSION}-${ENTGEN_SRC_HASH}"

if [ ! -x "${ENTGEN_BIN}" ]; then
  echo "[entgen] building generator pinned to ent ${ENT_VERSION}"
  (cd "${BACKEND_DIR}" && go build -tags entgen -o "${ENTGEN_BIN}" ./cmd/entgen)
fi

available_mb() {
  if command -v vm_stat >/dev/null 2>&1; then
    vm_stat | awk '/Pages free/{f=$3} /Pages inactive/{i=$3} END {printf "%.0f", (f+i)*4096/1048576}'
  else
    free -m | awk '/^Mem:/{printf "%.0f", $7}'
  fi
}

MIN_FREE_MB="${ENTGEN_MIN_FREE_MB:-6000}"
if [ "${ENTGEN_SKIP_MEM_CHECK:-0}" != "1" ]; then
  AVAILABLE_MB="$(available_mb)"
  if [ "${AVAILABLE_MB}" -lt "${MIN_FREE_MB}" ]; then
    echo "[entgen] abort: only ${AVAILABLE_MB} MB reclaimable memory, need ${MIN_FREE_MB} MB." >&2
    echo "[entgen] close Docker/IDE/browser, or set ENTGEN_MIN_FREE_MB to override." >&2
    exit 1
  fi
fi

# Each run gets its own staging directory. Nothing is ever bulk-deleted: the
# old runs stay in the gitignored cache until the user reclaims .cache, and
# parallel worktrees/sessions cannot clobber each other's staging output.
STAGE_DIR="$(mktemp -d "${STAGE_ROOT}/stage-XXXXXX")"

echo "[entgen] generating into ${STAGE_DIR}"
echo "[entgen] log: ${LOG_FILE}"
if ! (cd "${BACKEND_DIR}" && "${ENTGEN_BIN}" -target "${STAGE_DIR}") >"${LOG_FILE}" 2>&1; then
  echo "[entgen] generation failed; ent/ was not touched. Last log lines:" >&2
  tail -40 "${LOG_FILE}" >&2
  exit 1
fi

for required in client.go mutation.go migrate/schema.go; do
  if [ ! -f "${STAGE_DIR}/${required}" ]; then
    echo "[entgen] staged output is incomplete: missing ${required}" >&2
    exit 1
  fi
done

python3 - "${BACKEND_DIR}" "${STAGE_DIR}" "${MODE}" <<'PY'
import hashlib
import os
import shutil
import sys
from pathlib import Path

backend, stage, mode = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
ent = backend / "ent"
header = b"// Code generated by ent, DO NOT EDIT."

def list_files(root):
    return {p.relative_to(root).as_posix(): p for p in root.rglob("*") if p.is_file()}

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

staged = list_files(stage)
current = list_files(ent)

bad = sorted(rel for rel, p in staged.items() if not p.read_bytes().startswith(header))
if bad:
    print("[entgen] staged files without the ent generated header:", file=sys.stderr)
    for rel in bad:
        print("  " + rel, file=sys.stderr)
    sys.exit(1)

changes = []
for rel, src in sorted(staged.items()):
    dst = ent / rel
    if not dst.exists() or digest(dst) != digest(src):
        changes.append(("A" if not dst.exists() else "M", rel))

for rel, dst in sorted(current.items()):
    if rel in staged or rel == "generate.go" or rel.startswith("schema/"):
        continue
    # Only generated leftovers are removable. Handwritten helpers (mixin/,
    # migrate/*_test.go, SQL migrations) do not carry the ent header.
    if dst.read_bytes().startswith(header):
        changes.append(("D", rel))

schema_count = len(list((backend / "ent" / "schema").glob("*.go")))
mutation = stage / "mutation.go"
mutation_lines = sum(1 for _ in mutation.open(encoding="utf-8"))

print(f"[entgen] schemas={schema_count} staged_files={len(staged)} mutation_lines={mutation_lines}")
for kind, rel in changes:
    print(f"  {kind} {rel}")
print(f"[entgen] {len(changes)} file(s) differ")

budget = int(os.environ.get("ENTGEN_MUTATION_BUDGET", "250000"))
if mutation_lines > budget:
    print(
        f"[entgen] BUDGET TRIPWIRE: mutation.go {mutation_lines} lines > {budget}. "
        "Start the domain-split plan (option B) before the next schema batch.",
        file=sys.stderr,
    )

if mode == "check":
    sys.exit(1 if changes else 0)

for kind, rel in changes:
    dst = ent / rel
    if kind == "D":
        dst.unlink()
    else:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(staged[rel], dst)
print("[entgen] synced into ent/")
PY
