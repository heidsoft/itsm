export function zhTranslate(template: string, replacements?: Record<string, unknown>): string {
  const translated = zhDictionary[template] ?? template;
  if (!replacements) {
    return translated;
  }
  return translated.replace(/\{([^}]+)\}/g, (match, key: string) => {
    const value = replacements[key];
    return value === undefined || value === null ? match : String(value);
  });
}

