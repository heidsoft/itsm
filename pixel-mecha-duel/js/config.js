MECHA.clamp = function (v, min, max) {
  return v < min ? min : v > max ? max : v;
};

MECHA.lerp = function (a, b, t) {
  return a + (b - a) * t;
};

MECHA.rand = function (min, max) {
  return min + Math.random() * (max - min);
};

MECHA.pick = function (arr) {
  return arr[(Math.random() * arr.length) | 0];
};

// 确定性伪随机（用于背景星空 / 观众，避免每帧闪烁）
MECHA.seeded = function (seed) {
  let s = seed >>> 0;
  return function () {
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};
